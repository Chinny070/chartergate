"""Evidence Vault integration tests: REAL web access, real leader + validator consensus.

Run against a local GLSim network (no Docker):

    glsim --port 4000 --validators 5 --no-browser
    gltest tests/integration/ -v -s

or against StudioNet (real GenVM, LLM-backed validators, a real browser for render):

    CHARTERGATE_REAL_GENVM=1 gltest tests/integration/ -v -s --network studionet

What can run where (verified in this environment)
-------------------------------------------------
* Tests WITHOUT `needs_real_genvm` run on GLSim. They use real `web.get` (HTTP via httpx), five
  validators that each re-fetch independently, and real consensus, and they never reach an LLM because
  the source is unreachable or unusable.
* Tests WITH `needs_real_genvm` cannot run on GLSim here, for two exact reasons:
    1. LLM: a VERIFIED / UNVERIFIABLE record needs extraction. GLSim's LLM providers need OPENAI_API_KEY
       or ANTHROPIC_API_KEY (glsim/live_io.py); neither is set, and none is borrowed.
    2. web.render: GLSim has no Playwright package or browser installed (and is started with --no-browser),
       so it falls back to a plain HTTP GET and returns text even for an unreachable host. Real GenVM
       raises on a failed render, so a render-failure test would not be testing the real behaviour.
  They are the StudioNet smoke cases.
* GLSim hands back an EMPTY schema for this contract (it does the same for the frozen Stage 1.2
  contract), so the fixture binds the deployed address to the official schema from `genvm-lint`.
* GLSim holds state across deployments in one process. For repeatable runs, start a fresh GLSim.

Stable public sources used: https://example.com/ (an IANA-maintained illustrative page) and a hostname
under the reserved `.invalid` TLD, which can never resolve.
"""

import json
import os
from pathlib import Path

import pytest
from gltest import get_contract_factory
from gltest.assertions import tx_execution_succeeded
from gltest.contracts.contract import Contract

# The official schema, generated by `genvm-lint schema` from the pinned runner. GLSim returns an EMPTY
# schema for this contract (it does the same for the frozen Stage 1.2 contract, so this is a GLSim /
# gltest limitation, not a Stage 2 regression), which leaves the deployed Contract object without
# methods. Binding the deployed address to the official schema restores them, and also makes these tests
# exercise the real schema.
SCHEMA = json.loads((Path(__file__).resolve().parents[2] / "docs" / "charter_gate.schema.json").read_text(encoding="utf-8"))

REAL_GENVM = os.environ.get("CHARTERGATE_REAL_GENVM") == "1"
needs_real_genvm = pytest.mark.skipif(
    not REAL_GENVM,
    reason="needs real GenVM (LLM validators + browser render); GLSim here has neither. Set CHARTERGATE_REAL_GENVM=1 on StudioNet",
)

EXAMPLE = "https://example.com/"
MISSING = "https://example.com/chartergate-stage2-this-page-does-not-exist"
UNRESOLVABLE = "https://chartergate-stage2-unresolvable.invalid/"


@pytest.fixture(scope="module")
def charter():
    factory = get_contract_factory("CharterGate")
    deployed = factory.deploy(args=["Atlas DAO", "A DAO that funds open-source infrastructure."])
    contract = Contract.new(address=deployed.address, schema=SCHEMA, account=deployed.account)
    assert tx_execution_succeeded(contract.add_charter_section(args=["s2", "Transparency", "Disclose allocations."]).transact())
    assert tx_execution_succeeded(contract.submit_proposal(args=["Fund Atlas", "Open-source tool", "Grant funding"]).transact())
    return contract


def submit(charter, url, kind, claim="The page states an allocation of 46%.", section="s2"):
    receipt = charter.submit_evidence(args=[1, url, kind, claim, section]).transact()
    assert tx_execution_succeeded(receipt), receipt
    count = charter.get_evidence_count(args=[]).call()
    return charter.get_evidence(args=[count]).call()


# ---- real web.get, no LLM needed -----------------------------------------------


def test_real_get_of_a_missing_page_finalizes_as_source_unavailable(charter):
    record = submit(charter, MISSING, "STATIC_WEB")
    assert record["status"] == "SOURCE_UNAVAILABLE"
    assert record["status_reason"] == "HTTP_404"
    assert record["retrieval_method"] == "GET"
    assert record["normalized_value"] == "" and record["excerpt"] == ""
    assert record["content_hash"].startswith("0x") and len(record["content_hash"]) == 66


def test_real_get_of_html_as_an_api_finalizes_as_invalid_source(charter):
    record = submit(charter, EXAMPLE, "API")
    assert record["status"] == "INVALID_SOURCE"
    assert record["status_reason"] == "INVALID_JSON"
    assert record["source_kind"] == "API" and record["retrieval_method"] == "GET"


# ---- real web.render: needs real GenVM (GLSim has no browser and returns text for dead hosts) ----


@needs_real_genvm
def test_real_render_of_an_unresolvable_host_finalizes_as_source_unavailable(charter):
    record = submit(charter, UNRESOLVABLE, "DYNAMIC_WEB")
    assert record["status"] == "SOURCE_UNAVAILABLE"
    assert record["retrieval_method"] == "RENDER_TEXT"


# ---- protocol timestamp and provenance --------------------------------------------


def test_record_carries_protocol_time_and_provenance(charter):
    record = submit(charter, MISSING, "STATIC_WEB")
    assert record["retrieved_at"] == record["created_at"]
    assert record["retrieved_at"][:4].isdigit() and record["retrieved_at"].endswith("Z")
    assert record["source_url"] == MISSING and record["proposal_id"] == 1
    assert record["related_section_id"] == "s2"
    assert record["related_revision_version"] == 2  # s2 as it read when proposal 1 was submitted


# ---- failures revert and consume nothing --------------------------------------------


def test_invalid_input_reverts_without_consuming_an_evidence_id(charter):
    before = charter.get_evidence_count(args=[]).call()
    receipt = charter.submit_evidence(args=[1, "http://localhost/admin", "STATIC_WEB", "claim", ""]).transact()
    assert not tx_execution_succeeded(receipt)
    assert charter.get_evidence_count(args=[]).call() == before


# ---- LLM-backed cases: the StudioNet smoke tests (need real GenVM) -------------------------


@needs_real_genvm
def test_real_get_verifies_a_stated_fact(charter):
    record = submit(
        charter,
        EXAMPLE,
        "STATIC_WEB",
        claim="The page says this domain is for use in illustrative examples in documents.",
    )
    assert record["status"] == "VERIFIED"
    assert record["retrieval_method"] == "GET"
    assert record["excerpt"] and record["normalized_fact"] and record["normalized_value"]


@needs_real_genvm
def test_real_render_verifies_a_stated_fact(charter):
    record = submit(
        charter,
        EXAMPLE,
        "DYNAMIC_WEB",
        claim="The page says this domain is for use in illustrative examples in documents.",
    )
    assert record["status"] == "VERIFIED"
    assert record["retrieval_method"] == "RENDER_TEXT"


@needs_real_genvm
def test_a_claim_the_page_does_not_support_is_never_verified(charter):
    record = submit(charter, EXAMPLE, "STATIC_WEB", claim="The page states a team token allocation of 46%.")
    assert record["status"] == "UNVERIFIABLE"
    assert record["status"] != "VERIFIED"
